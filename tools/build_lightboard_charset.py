#!/usr/bin/env python3
"""Generate identical C/JS BMP bitmaps from the verified font probe's cmap."""
import base64
import json
from pathlib import Path


def main():
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font_probe", type=Path)
    args = parser.parse_args()
    points = json.loads(args.font_probe.read_text())["codepoints"]
    bits = bytearray(8192)
    for cp in points:
        if not 32 <= cp < 65536:
            raise ValueError("Only printable BMP coverage is supported")
        bits[cp // 8] |= 1 << (cp % 8)
    Path("main/services/lightboard").mkdir(exist_ok=True)
    Path("main/services/lightboard/lightboard_charset.inc").write_text(
        "// Generated by tools/build_lightboard_charset.py from the verified font cmap.\n" +
        ",\n".join(",".join(f"0x{x:02x}" for x in bits[i:i + 16]) for i in range(0, len(bits), 16)) + "\n")
    encoded = json.dumps(base64.b64encode(bits).decode())
    Path("main/web/badge/lightboard_charset.js").write_text(
        '(function(root){"use strict";\n// Generated BMP coverage, identical to lightboard_charset.inc.\n'
        f'const bits=Uint8Array.from(atob({encoded}),c=>c.charCodeAt(0));\n'
        'const api={version:1,supports:cp=>Number.isInteger(cp)&&cp>=0&&cp<65536&&!!(bits[cp>>>3]&(1<<(cp&7)))};\n'
        'root.LightboardCharset=api;if(typeof module!=="undefined")module.exports=api;\n})(globalThis);\n')


if __name__ == "__main__":
    main()
